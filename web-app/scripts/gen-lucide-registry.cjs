// Generates src/utils/lucideRegistry.ts — the subset of lucide-react icons that can be looked up
// by NAME at runtime. Sources: static `LucideIcons.X` use, and every PascalCase string literal in
// src that is a lucide export (picker lists, trait/icon tables, defaults), plus EXTRA below.
//   node scripts/gen-lucide-registry.cjs
const fs = require('fs'), path = require('path');
const root = path.resolve(__dirname, '..');
const lucide = require(path.join(root, 'node_modules/lucide-react'));
const all = new Set(Object.keys(lucide).filter(k => /^[A-Z]/.test(k) && !/Icon$/.test(k) && !k.startsWith('Lucide') && k !== 'Icon'));

// Icon names that users may already have saved but that no longer appear as a literal in src.
const EXTRA = [];

const names = new Set(EXTRA.filter(n => all.has(n)));
const files = [];
(function walk(d) {
  for (const f of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, f.name);
    if (f.isDirectory()) walk(p);
    else if (/\.(ts|tsx)$/.test(f.name) && f.name !== 'lucideRegistry.ts') files.push(p);
  }
})(path.join(root, 'src'));
for (const f of files) {
  const s = fs.readFileSync(f, 'utf8');
  for (const m of s.matchAll(/LucideIcons\.([A-Z][A-Za-z0-9]*)/g)) all.has(m[1]) && names.add(m[1]);
  for (const m of s.matchAll(/['"`]([A-Z][A-Za-z0-9]{2,40})['"`]/g)) all.has(m[1]) && names.add(m[1]);
}
const sorted = [...names].sort();
fs.writeFileSync(path.join(root, 'src/utils/lucideRegistry.ts'),
`// AUTO-GENERATED by scripts/gen-lucide-registry.cjs — do not edit by hand.
//
// The subset of lucide-react that can be looked up BY NAME at runtime (icon pickers, icons stored
// on habits/projects/traits, config tables). \`import * as LucideIcons from 'lucide-react'\` used to
// drag all ~${all.size} icons into the bundle; this re-exports only the ${sorted.length} that can be referenced.
//
// If an icon you reference by name does not render, add it to EXTRA in the generator and re-run:
//   node scripts/gen-lucide-registry.cjs
export {
${sorted.map(n => '  ' + n + ',').join('\n')}
} from 'lucide-react';
`);
console.log(`registry: ${sorted.length} of ${all.size} lucide icons`);
